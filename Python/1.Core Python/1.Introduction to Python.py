# -----What is Programming Language
#
# -Programming Language is the way for Developers Which is used to communicate with Compiler/Machine/System
# -It has set of rules that can be understand by computer and execute them.
#
# ------There are two different types of Language
#
# 1,High Level Language
#  High Level Language is a Human Understandable Language but not by System(CPU)
#  Ex: C,C++,JAVA,PYTHON,php.
#
# 2,Low Level Language
#   Low Level Language is a Machine Understandable Language which was binary format (0 & 1)
#
# -----What is Translator
#  It is a tool which is used to Convert one Language into another Language.
#
#
#  Translator Classified into two types
#
#  1,Compiler
#  It is a Software/Program which is used translate source code into  Machine code at a time
#  Ex: C,C++, JAVA
#
#  2,Interpreter
#  It is a Software / Program which is execute(run)  source code into Machine code line by line
#  Ex: Python
#
